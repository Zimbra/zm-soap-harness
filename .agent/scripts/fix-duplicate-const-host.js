#!/usr/bin/env node
/**
 * Fix duplicate `const` variable declarations in JS test files.
 *
 * The add-zimbra-mail-host.js script generates identical variable names
 * (host, createAcctRes, acctInfo, acctInfoRes) for each account creation.
 * When multiple accounts are created in the same scope, this causes
 * JavaScript SyntaxErrors (Cannot redeclare block-scoped variable).
 *
 * Fix: Rename subsequent declarations and all their references within
 * the same scope block to use numbered suffixes (host2, host3, etc.).
 *
 * USAGE:
 *   node .agent/scripts/fix-duplicate-const-host.js --dry-run
 *   node .agent/scripts/fix-duplicate-const-host.js
 */

const fs = require('fs');
const path = require('path');

const JS_BASE = 'mocha/tests';
const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');

const C = {
    green: s => `\x1b[32m${s}\x1b[0m`,
    yellow: s => `\x1b[33m${s}\x1b[0m`,
    red: s => `\x1b[31m${s}\x1b[0m`,
    bold: s => `\x1b[1m${s}\x1b[0m`,
};

function findFiles(dir, ext) {
    const results = [];
    if (!fs.existsSync(dir)) return results;
    function walk(d) {
        for (const entry of fs.readdirSync(d, { withFileTypes: true })) {
            const full = path.join(d, entry.name);
            if (entry.isDirectory()) walk(full);
            else if (entry.name.endsWith(ext)) results.push(full.replace(/\\/g, '/'));
        }
    }
    walk(dir);
    return results.sort();
}

function getIndent(line) {
    const m = line.match(/^(\s*)/);
    return m ? m[1].length : 0;
}

/**
 * Check if a line is a scope boundary (entering/exiting a function scope).
 * Uses line patterns instead of brace counting to avoid template literal issues.
 */
function isScopeBoundary(line, refIndent) {
    // Scope closer: }); or }) at indentation strictly less than reference
    if (/^\s*\}\)\s*;?\s*$/.test(line) && getIndent(line) < refIndent) {
        return true;
    }
    // Mocha scope openers
    if (/^\s*(it|before|beforeEach|after|afterEach|describe)\s*\(/.test(line)) {
        return true;
    }
    // Standalone function declaration
    if (/^\s*(async\s+)?function\s+\w+/.test(line)) {
        return true;
    }
    return false;
}

// Variables generated by add-zimbra-mail-host.js that may be duplicated.
// Order matters: process outer vars first so inner refs get updated correctly.
const TARGET_VARS = ['createAcctRes', 'acctInfoRes', 'acctInfo', 'host'];

/**
 * For the last duplicate in a scope group, find where its usage region ends.
 * Region = declaration line through last reference line before scope boundary.
 */
function findRegionEnd(lines, startLine, varName) {
    const refIndent = getIndent(lines[startLine]);
    const wordRegex = new RegExp(`\\b${varName}\\b`);
    let lastRef = startLine;

    for (let i = startLine + 1; i < lines.length; i++) {
        if (isScopeBoundary(lines[i], refIndent)) break;
        if (wordRegex.test(lines[i])) {
            lastRef = i;
        }
        // Stop searching after 10 lines without a reference
        if (i - lastRef > 10) break;
    }
    return lastRef + 1; // exclusive
}

function fixFile(filepath) {
    let lines = fs.readFileSync(filepath, 'utf8').split('\n');
    let anyChange = false;

    for (const varName of TARGET_VARS) {
        const declRegex = new RegExp(`^(\\s*)const\\s+${varName}\\s*=`);

        // Find all declaration lines for this variable
        const declLines = [];
        for (let i = 0; i < lines.length; i++) {
            if (declRegex.test(lines[i])) {
                declLines.push(i);
            }
        }
        if (declLines.length <= 1) continue;

        // Group declarations by scope
        const scopeGroups = [[declLines[0]]];
        for (let k = 1; k < declLines.length; k++) {
            const prevIdx = declLines[k - 1];
            const currIdx = declLines[k];
            const currIndent = getIndent(lines[currIdx]);

            let newScope = false;
            for (let j = prevIdx + 1; j < currIdx; j++) {
                if (isScopeBoundary(lines[j], currIndent)) {
                    newScope = true;
                    break;
                }
            }

            if (newScope) {
                scopeGroups.push([currIdx]);
            } else {
                scopeGroups[scopeGroups.length - 1].push(currIdx);
            }
        }

        // For groups with 2+ declarations, rename duplicates
        for (const group of scopeGroups) {
            if (group.length <= 1) continue;

            for (let k = 1; k < group.length; k++) {
                const suffix = k + 1;
                const newVarName = `${varName}${suffix}`;
                const regionStart = group[k];
                const regionEnd = (k + 1 < group.length)
                    ? group[k + 1]
                    : findRegionEnd(lines, regionStart, varName);

                // Replace varName → newVarName using word boundaries
                const wordRegex = new RegExp(`\\b${varName}\\b`, 'g');
                for (let j = regionStart; j < regionEnd; j++) {
                    const newLine = lines[j].replace(wordRegex, newVarName);
                    if (newLine !== lines[j]) {
                        lines[j] = newLine;
                        anyChange = true;
                    }
                }
            }
        }
    }

    return anyChange ? lines.join('\n') : null;
}

// =============================================================================
// MAIN
// =============================================================================
let totalFixed = 0;
const jsFiles = findFiles(JS_BASE, '.js');
console.log(C.bold(`\n  Fixing duplicate const declarations (${jsFiles.length} files)\n`));

for (const filepath of jsFiles) {
    const rel = filepath.replace(JS_BASE + '/', '');
    const result = fixFile(filepath);
    if (result) {
        if (!dryRun) {
            fs.writeFileSync(filepath, result, 'utf8');
        }
        totalFixed++;
        console.log(C.green(`  ✅ FIXED: ${rel}${dryRun ? ' (dry-run)' : ''}`));
    }
}

console.log('');
console.log(C.bold('  Summary:'));
console.log(`    Fixed: ${totalFixed}`);
console.log(`    Total: ${jsFiles.length}`);
console.log('');
